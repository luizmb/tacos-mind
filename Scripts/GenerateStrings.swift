#!/usr/bin/env swift
// Writes `L.swift` from the app's string catalog, so every string on screen is a token:
// `Text(L.Home.newModel)` rather than `Text("New Model")`.
//
//     swift Scripts/GenerateStrings.swift Sources/App/Localizable.xcstrings Sources/ArticleEditor/Localization/L.swift
//
// The catalog's keys are the English text (so an untranslated key, or a test without the app's
// bundle, still reads in English); each entry's comment names its token, `L.Home.newModel`.
// A key with `%@`, `%lld` or `%u` becomes a function taking a `String`, an `Int` or a `UInt32` for
// each, in order.
import Foundation

struct Entry {
    let path: [String]
    let key: String
}

let arguments = CommandLine.arguments.dropFirst()
guard arguments.count == 2, let catalogPath = arguments.first, let outputPath = arguments.last else {
    FileHandle.standardError.write(Data("usage: GenerateStrings.swift <Localizable.xcstrings> <L.swift>\n".utf8))
    exit(1)
}

let data = try Data(contentsOf: URL(fileURLWithPath: catalogPath))
let catalog = try JSONSerialization.jsonObject(with: data) as? [String: Any] ?? [:]
let strings = catalog["strings"] as? [String: [String: Any]] ?? [:]

let entries: [Entry] = strings.compactMap { key, value in
    guard let comment = value["comment"] as? String, comment.hasPrefix("L.") else { return nil }
    return Entry(path: comment.split(separator: ".").dropFirst().map(String.init), key: key)
}
.sorted { $0.path.joined(separator: ".") < $1.path.joined(separator: ".") }

/// The key as Swift string literal content, its format specifiers replaced by interpolations of
/// the function's arguments; and those arguments' types.
func literal(_ key: String) -> (body: String, parameters: [String]) {
    var body = ""
    var parameters: [String] = []
    var index = key.startIndex
    while index < key.endIndex {
        let rest = key[index...]
        if rest.hasPrefix("%@") {
            parameters.append("String")
            body += "\\(a\(parameters.count))"
            index = key.index(index, offsetBy: 2)
        } else if rest.hasPrefix("%lld") {
            parameters.append("Int")
            body += "\\(a\(parameters.count))"
            index = key.index(index, offsetBy: 4)
        } else if rest.hasPrefix("%u") {
            parameters.append("UInt32")
            body += "\\(a\(parameters.count))"
            index = key.index(index, offsetBy: 2)
        } else if rest.hasPrefix("%%") {
            body += "%"
            index = key.index(index, offsetBy: 2)
        } else {
            let character = key[index]
            switch character {
            case "\\": body += "\\\\"
            case "\"": body += "\\\""
            case "\n": body += "\\n"
            default: body.append(character)
            }
            index = key.index(after: index)
        }
    }
    return (body, parameters)
}

/// Nested enums, one per path component but the last.
final class Node {
    var children: [String: Node] = [:]
    var leaves: [(name: String, key: String)] = []
}

let root = Node()
for entry in entries {
    var node = root
    for component in entry.path.dropLast() {
        node = node.children[component] ?? { let child = Node(); node.children[component] = child; return child }()
    }
    node.leaves.append((entry.path.last ?? "", entry.key))
}

/// `type` is `LocalizedStringKey` for views, `LocalizedStringResource` for state.
func render(_ node: Node, indent: String, type: String) -> String {
    let leaves = node.leaves.sorted { $0.name < $1.name }.map { leaf -> String in
        let (body, parameters) = literal(leaf.key)
        if parameters.isEmpty {
            return "\(indent)public static var \(leaf.name): \(type) { \"\(body)\" }"
        }
        let list = parameters.enumerated().map { "_ a\($0.offset + 1): \($0.element)" }.joined(separator: ", ")
        return "\(indent)public static func \(leaf.name)(\(list)) -> \(type) { \"\(body)\" }"
    }
    let children = node.children.keys.sorted().map { name in
        "\(indent)public enum \(name) {\n\(render(node.children[name] ?? Node(), indent: indent + "    ", type: type))\n\(indent)}"
    }
    return (leaves + children).joined(separator: "\n")
}

let output = """
// Generated by Scripts/GenerateStrings.swift from Localizable.xcstrings. Don't edit: change the
// catalog and run the script.

import SwiftUI

/// Every string on screen, by token. The text is the catalog's, in the reader's language.
public enum L {
\(render(root, indent: "    ", type: "LocalizedStringKey"))

    /// The same strings as resources, for state (a resource is `Sendable` and `Hashable`, and
    /// `Text` shows it in the reader's language).
    public enum Resource {
\(render(root, indent: "        ", type: "LocalizedStringResource"))
    }
}

"""
let existing = try? String(contentsOfFile: outputPath, encoding: .utf8)
if existing != output {
    try output.write(toFile: outputPath, atomically: true, encoding: .utf8)
}
print("\(entries.count) strings")
